from pathlib import Path
from typing import Any
import math

import joblib
import numpy as np
import pandas as pd
import streamlit as st


MODEL_PATH = Path(__file__).resolve().with_name("indian.pkl")

st.set_page_config(
    page_title="India ML Studio",
    page_icon="📈",
    layout="wide",
)


@st.cache_resource
def load_model(model_path: str, modified_ns: int, file_size: int) -> Any:
    return joblib.load(model_path)


st.title("India ML Studio")
st.caption("A simple interface for generating predictions with your trained model.")

if not MODEL_PATH.is_file():
    st.error(f"Model file not found: {MODEL_PATH.name}")
    st.stop()

model_stat = MODEL_PATH.stat()
model = load_model(
    str(MODEL_PATH),
    model_stat.st_mtime_ns,
    model_stat.st_size,
)

feature_count = int(getattr(model, "n_features_in_", 0))
stored_feature_names = getattr(model, "feature_names_in_", None)

if stored_feature_names is not None:
    feature_names = [str(name) for name in stored_feature_names]
else:
    feature_names = [f"Feature {index + 1}" for index in range(feature_count)]

if not feature_names:
    st.error("The model does not expose any input features.")
    st.stop()

if feature_count and len(feature_names) != feature_count:
    st.error("The model's feature metadata is inconsistent.")
    st.stop()

with st.sidebar:
    st.subheader("Model details")
    st.write(f"**Model:** {type(model).__name__}")
    st.write(f"**Input features:** {len(feature_names)}")
    st.write(f"**Model file:** `{MODEL_PATH.name}`")
    st.divider()
    st.caption(
        "Predictions are generated by the bundled model. "
        "Only load model files you trust."
    )

st.subheader("Enter feature values")
st.write("Provide a numeric value for each feature, then run the model.")

input_values: list[float] = []
columns = st.columns(min(len(feature_names), 3))
for index, feature_name in enumerate(feature_names):
    default_value = 2026.0 if feature_name.strip().lower() == "year" else 0.0
    with columns[index % len(columns)]:
        input_values.append(
            st.number_input(
                feature_name.replace("_", " ").strip().title(),
                value=default_value,
                step=1.0,
                key=f"feature_input_{index}",
            )
        )

if st.button("Generate prediction", type="primary", use_container_width=True):
    if not all(math.isfinite(value) for value in input_values):
        st.error("Enter a finite numeric value for every feature.")
    else:
        model_input = pd.DataFrame([input_values], columns=feature_names)
        prediction = model.predict(model_input)
        result = np.asarray(prediction)
        st.divider()
        st.subheader("Prediction")
        if result.size == 1:
            st.metric("Model output", f"{float(result.reshape(-1)[0]):,.4f}")
        else:
            st.write("Model output")
            st.json(result[0].tolist())

        with st.expander("View submitted inputs"):
            st.json(dict(zip(feature_names, input_values)))